// Generic tabular export (XLSX / CSV / PDF) used by lists and reports.
const path = require('path');
const ExcelJS = require('exceljs');
const PDFDocument = require('pdfkit');

const BRAND = { purple: '#5A4293', navy: '#2D3D62', gray: '#D0D2D3' };
const LOGO = path.join(__dirname, '../../assets/logo-horizontal.png');

const cell = (row, col) => {
  const v = typeof col.value === 'function' ? col.value(row) : row[col.key];
  if (v === null || v === undefined) return '';
  if (v instanceof Date) return v.toISOString().slice(0, 10);
  if (typeof v === 'object' && typeof v.toFixed === 'function') return Number(v.toString());
  return v;
};

const sendXlsx = async (res, { title, columns, rows, filename }) => {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'SEEDA HRMS';
  const ws = wb.addWorksheet((title || 'Report').slice(0, 30));
  ws.columns = columns.map((c) => ({ header: c.header, key: c.key || c.header, width: c.width || 18 }));
  ws.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
  ws.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF5A4293' } };
  rows.forEach((r) => ws.addRow(columns.map((c) => cell(r, c))));
  ws.views = [{ state: 'frozen', ySplit: 1 }];
  res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
  res.setHeader('Content-Disposition', `attachment; filename="${filename || 'export'}.xlsx"`);
  await wb.xlsx.write(res);
  res.end();
};

const csvEscape = (v) => {
  let s = String(v ?? '');
  if (/^[=+\-@]/.test(s)) s = `'${s}`; // CSV/formula injection guard
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

const sendCsv = (res, { columns, rows, filename }) => {
  const lines = [columns.map((c) => csvEscape(c.header)).join(',')];
  rows.forEach((r) => lines.push(columns.map((c) => csvEscape(cell(r, c))).join(',')));
  res.setHeader('Content-Type', 'text/csv; charset=utf-8');
  res.setHeader('Content-Disposition', `attachment; filename="${filename || 'export'}.csv"`);
  res.send(`﻿${lines.join('\n')}`);
};

// PDF tables use Latin text; Arabic-script values are exported via XLSX/CSV or the in-app print view
// (pdfkit has no Arabic shaping — documented in KNOWN_ISSUES).
const sendPdf = (res, { title, subtitle, columns, rows, filename }) => {
  const doc = new PDFDocument({ size: 'A4', layout: columns.length > 6 ? 'landscape' : 'portrait', margin: 36 });
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="${filename || 'export'}.pdf"`);
  doc.pipe(res);
  const W = doc.page.width - 72;
  try { doc.image(LOGO, 36, 28, { height: 30 }); } catch { /* logo optional */ }
  doc.fillColor(BRAND.navy).fontSize(16).text(title || 'Report', 36, 70);
  if (subtitle) doc.fillColor('#666').fontSize(9).text(subtitle);
  doc.moveDown(0.5);
  const colW = W / columns.length;
  const drawHeader = () => {
    const y = doc.y;
    doc.rect(36, y, W, 18).fill(BRAND.purple);
    doc.fillColor('#fff').fontSize(8);
    columns.forEach((c, i) => doc.text(String(c.header), 40 + i * colW, y + 5, { width: colW - 6, ellipsis: true, lineBreak: false }));
    doc.y = y + 20;
  };
  drawHeader();
  rows.forEach((r, idx) => {
    if (doc.y > doc.page.height - 60) { doc.addPage(); drawHeader(); }
    const y = doc.y;
    if (idx % 2) doc.rect(36, y - 2, W, 16).fill('#F4F2F9');
    doc.fillColor('#222').fontSize(8);
    columns.forEach((c, i) => doc.text(String(cell(r, c)), 40 + i * colW, y + 2, { width: colW - 6, ellipsis: true, lineBreak: false }));
    doc.y = y + 16;
  });
  doc.fillColor('#999').fontSize(7).text(`Generated by SEEDA HRMS — ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC`, 36, doc.page.height - 40);
  doc.end();
};

// JSON report shape shared by every module: { columns: [header], rows: [[value]] }
const table = (columns, rows) => ({ columns: columns.map((c) => c.header), rows: rows.map((r) => columns.map((c) => cell(r, c))) });

const send = (res, format, opts) => {
  if (format === 'xlsx') return sendXlsx(res, opts);
  if (format === 'csv') return sendCsv(res, opts);
  if (format === 'pdf') return sendPdf(res, opts);
  return res.json({ items: opts.rows });
};

module.exports = { send, table, sendXlsx, sendCsv, sendPdf, BRAND, LOGO };
